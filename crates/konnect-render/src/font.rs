/// Width of `text` in cell units.
pub(crate) fn text_width(text: &str) -> f32 {
    let n = text.chars().count() as f32;
    if n == 0.0 {
        0.0
    } else {
        n * ADVANCE - 1.0
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_ascii_character_has_strokes_or_is_a_space() {
        for c in (0x20u8..0x7f).map(char::from) {
            match glyph(c) {
                None => assert_eq!(c, ' '),
                Some(strokes) => {
                    assert!(!strokes.is_empty(), "{c:?}");
                    for s in strokes {
                        assert!(s.len() >= 2, "{c:?} has a one-point stroke");
                        for &(x, y) in *s {
                            assert!(
                                (0.0..=4.0).contains(&x) && (0.0..=7.0).contains(&y),
                                "{c:?}"
                            );
                        }
                    }
                }
            }
        }
        assert_eq!(glyph('a'), glyph('A'));
        assert_eq!(text_width("AB"), 9.0);
    }
}
