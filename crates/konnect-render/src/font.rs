//! A small built-in stroke font for raster labels.
//!
//! The renderer never consults system fonts (see the crate docs), so labels
//! on a board render are drawn from these strokes: each glyph is a few
//! polylines on a 4 × 6 cell (x right, y down, the baseline at y = 6),
//! advanced by 5 units. Lower case renders as upper case; a character the
//! table lacks renders as an open box, never as nothing.

/// One glyph: polylines of `(x, y)` cell points.
pub(crate) type Glyph = &'static [&'static [(f32, f32)]];

/// Cell width plus spacing, in cell units.
pub(crate) const ADVANCE: f32 = 5.0;
/// Cap height in cell units.
pub(crate) const HEIGHT: f32 = 6.0;

const UNKNOWN: Glyph = &[&[(0.0, 0.0), (4.0, 0.0), (4.0, 6.0), (0.0, 6.0), (0.0, 0.0)]];

